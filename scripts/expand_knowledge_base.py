def main():
    print("=" * 60)
    print("SOBATPAWS KNOWLEDGE BASE EXPANSION")
    print("=" * 60)
    
    for species, diseases in EXPANDED_DISEASES.items():
        if species not in ['dog', 'cat']:
            continue
        
        # Map species to filename
        species_map = {
            'dog': 'diseases_dogs.json',
            'cat': 'diseases_cats.json',
        }
        
        filename = species_map[species]
        filepath = os.path.join(CLINICAL_DIR, filename)
        
        # Load existing
        with open(filepath) as f:
            existing = json.load(f)
        
        existing_slugs = {d['slug'] for d in existing['diseases']}
        new_count = 0
        updated_count = 0
        
        for new_disease in diseases:
            if new_disease['slug'] in existing_slugs:
                # Update existing
                for i, d in enumerate(existing['diseases']):
                    if d['slug'] == new_disease['slug']:
                        existing['diseases'][i] = new_disease
                        updated_count += 1
                        break
            else:
                existing['diseases'].append(new_disease)
                new_count += 1
        
        with open(filepath, 'w') as f:
            json.dump(existing, f, indent=2, ensure_ascii=False)
        
        print(f"\n{species.upper()}:")
        print(f"  File: {filename}")
        print(f"  New diseases added: {new_count}")
        print(f"  Existing updated: {updated_count}")
        print(f"  Total diseases: {len(existing['diseases'])}")
    
    print("\n" + "=" * 60)
    print("EXPANSION COMPLETE")
    print("=" * 60)

if __name__ == '__main__':
    main()
